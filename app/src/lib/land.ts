function inside(lon: number, lat: number, ring: [number, number][]): boolean {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

let dots: { lat: number; lon: number }[] | null = null;

/** Land as evenly spaced dots, worked out once. */
export function landDots(step = 2.6): { lat: number; lon: number }[] {
  if (dots) return dots;
  dots = [];
  for (let lat = -58; lat <= 84; lat += step) {
    const lonStep = step / Math.max(0.2, Math.cos((lat * Math.PI) / 180));
    for (let lon = -180; lon < 180; lon += lonStep) if (LAND.some((r) => inside(lon, lat, r))) dots.push({ lat, lon });
  }
  return dots;
}
